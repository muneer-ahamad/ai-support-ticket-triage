from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from app.llm import GeminiClient  # noqa: E402
from app.nodes.classify import classify_node  # noqa: E402
from app.retriever import KnowledgeBase  # noqa: E402


def pct(n: int, d: int) -> float:
    return round((n / d) * 100, 2) if d else 0.0


def main() -> None:
    dataset_path = ROOT / "data" / "tickets_labeled.json"
    rows = json.loads(dataset_path.read_text(encoding="utf-8"))

    llm = GeminiClient()
    kb = KnowledgeBase(llm)
    kb.ensure_indexed()

    results: list[dict] = []
    class_correct = 0
    priority_correct = 0
    retrieval_hits = 0
    confusion: Counter[tuple[str, str]] = Counter()

    for row in rows:
        state = {"subject": row["subject"], "body": row["body"]}
        pred = classify_node(state, llm)
        docs = kb.search(f"{row['subject']}\n{row['body']}", top_k=3)
        retrieved_titles = [doc.title for doc in docs]

        category_ok = pred["category"] == row["category"]
        priority_ok = pred["priority"] == row["priority"]
        retrieval_ok = row["expected_kb_title"] in retrieved_titles

        class_correct += int(category_ok)
        priority_correct += int(priority_ok)
        retrieval_hits += int(retrieval_ok)
        confusion[(row["category"], pred["category"])] += 1

        results.append(
            {
                "id": row["id"],
                "expected_category": row["category"],
                "predicted_category": pred["category"],
                "expected_priority": row["priority"],
                "predicted_priority": pred["priority"],
                "confidence": pred["classification_confidence"],
                "category_correct": category_ok,
                "priority_correct": priority_ok,
                "expected_kb_title": row["expected_kb_title"],
                "retrieved_titles": retrieved_titles,
                "retrieval_hit_at_3": retrieval_ok,
            }
        )

    summary = {
        "examples": len(rows),
        "classification_accuracy_pct": pct(class_correct, len(rows)),
        "priority_accuracy_pct": pct(priority_correct, len(rows)),
        "retrieval_hit_at_3_pct": pct(retrieval_hits, len(rows)),
    }

    out_json = ROOT / "evals" / "results.json"
    out_json.write_text(json.dumps({"summary": summary, "results": results}, indent=2), encoding="utf-8")

    lines = [
        "# Evaluation Results",
        "",
        "> Generated by `python evals/run_evals.py`. Results depend on the configured Gemini model and may vary slightly across model updates.",
        "",
        "| Metric | Score |",
        "|---|---:|",
        f"| Classification accuracy | {summary['classification_accuracy_pct']}% |",
        f"| Priority accuracy | {summary['priority_accuracy_pct']}% |",
        f"| Retrieval hit@3 | {summary['retrieval_hit_at_3_pct']}% |",
        "",
        "## Misclassifications",
        "",
    ]
    misses = [r for r in results if not r["category_correct"]]
    if not misses:
        lines.append("No category misclassifications in this run.")
    else:
        for item in misses:
            lines.append(
                f"- `{item['id']}` expected `{item['expected_category']}`, got `{item['predicted_category']}` "
                f"(confidence {item['confidence']:.2f})."
            )

    (ROOT / "evals" / "results.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(json.dumps(summary, indent=2))
    print(f"Wrote {out_json} and evals/results.md")


if __name__ == "__main__":
    main()
